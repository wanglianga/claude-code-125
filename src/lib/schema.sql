-- 校园校服订购尺码试穿与售后换码平台 数据库结构
-- 所有表使用 IF NOT EXISTS，保证容器启动脚本可重复执行

CREATE TABLE IF NOT EXISTS campuses (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) UNIQUE NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  name VARCHAR(50) NOT NULL,
  role ENUM('ADMIN','TEACHER','PARENT','SUPPLIER','FACTORY','SERVICE') NOT NULL,
  campus_id INT NULL,
  supplier_id INT NULL,
  phone VARCHAR(30) NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS suppliers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  contact VARCHAR(50),
  phone VARCHAR(30),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS grades (
  id INT AUTO_INCREMENT PRIMARY KEY,
  campus_id INT NOT NULL,
  name VARCHAR(50) NOT NULL,
  is_graduating TINYINT DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS classes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  grade_id INT NOT NULL,
  name VARCHAR(50) NOT NULL,
  teacher_id INT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS students (
  id INT AUTO_INCREMENT PRIMARY KEY,
  class_id INT NOT NULL,
  student_no VARCHAR(30) UNIQUE NOT NULL,
  name VARCHAR(50) NOT NULL,
  gender VARCHAR(10) DEFAULT '男',
  parent_id INT NULL,
  is_poverty TINYINT DEFAULT 0,
  status ENUM('ACTIVE','TRANSFERRED') DEFAULT 'ACTIVE',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS order_plans (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(100) NOT NULL,
  campus_id INT NOT NULL,
  season VARCHAR(20) NOT NULL,
  status ENUM('DRAFT','OPEN','FITTING','ORDERING','PRODUCING','DISTRIBUTING','COMPLETED','CLOSED') DEFAULT 'DRAFT',
  pay_deadline DATE NULL,
  poverty_discount INT DEFAULT 50 COMMENT '贫困生减免百分比',
  remark VARCHAR(255),
  created_by INT,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS plan_classes (
  plan_id INT NOT NULL,
  class_id INT NOT NULL,
  PRIMARY KEY (plan_id, class_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS plan_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  plan_id INT NOT NULL,
  name VARCHAR(50) NOT NULL,
  category ENUM('SUIT','SPORT','FORMAL','EXTRA') NOT NULL COMMENT '套装/运动服/礼服/增购件',
  part ENUM('TOP','PANTS','SKIRT','COAT','SHOES','SET','OTHER') NOT NULL DEFAULT 'OTHER',
  price DECIMAL(10,2) NOT NULL,
  required TINYINT DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS measurements (
  id INT AUTO_INCREMENT PRIMARY KEY,
  student_id INT NOT NULL,
  plan_id INT NOT NULL,
  height DECIMAL(5,1),
  weight DECIMAL(5,1),
  usual_top VARCHAR(10),
  usual_bottom VARCHAR(10),
  usual_shoes VARCHAR(10),
  special_fit TINYINT DEFAULT 0,
  special_note VARCHAR(255),
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_m (student_id, plan_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS fitting_sessions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  plan_id INT NOT NULL,
  class_id INT NOT NULL,
  slot_start DATETIME NOT NULL,
  slot_end DATETIME NOT NULL,
  location VARCHAR(100),
  created_by INT,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS fitting_records (
  id INT AUTO_INCREMENT PRIMARY KEY,
  session_id INT NOT NULL,
  student_id INT NOT NULL,
  staff_id INT,
  top_size VARCHAR(10), pants_size VARCHAR(10), skirt_size VARCHAR(10),
  coat_size VARCHAR(10), shoe_size VARCHAR(10),
  note VARCHAR(255),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_fr (session_id, student_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS production_batches (
  id INT AUTO_INCREMENT PRIMARY KEY,
  batch_no VARCHAR(30) UNIQUE NOT NULL,
  plan_id INT NOT NULL,
  supplier_id INT NOT NULL,
  status ENUM('PENDING','IN_PRODUCTION','PRODUCED','SHIPPING','ARRIVED','CLOSED') DEFAULT 'PENDING',
  expected_arrival DATE NULL,
  note VARCHAR(255),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS orders (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_no VARCHAR(30) UNIQUE NOT NULL,
  plan_id INT NOT NULL,
  student_id INT NOT NULL,
  parent_id INT NOT NULL,
  batch_id INT NULL,
  status ENUM('CONFIRMED','CANCELLED') DEFAULT 'CONFIRMED',
  total_amount DECIMAL(10,2) NOT NULL,
  discount_amount DECIMAL(10,2) DEFAULT 0,
  final_amount DECIMAL(10,2) NOT NULL,
  pay_status ENUM('UNPAID','PAID','REFUNDED','PARTIAL_REFUND') DEFAULT 'UNPAID',
  paid_at DATETIME NULL,
  is_late TINYINT DEFAULT 0 COMMENT '迟缴费标记',
  note VARCHAR(255),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_order (plan_id, student_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS order_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL,
  plan_item_id INT NOT NULL,
  item_name VARCHAR(50),
  category VARCHAR(20),
  part VARCHAR(20),
  size VARCHAR(20),
  qty INT DEFAULT 1,
  price DECIMAL(10,2) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS payments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL,
  amount DECIMAL(10,2) NOT NULL,
  type ENUM('PAY','REFUND') NOT NULL,
  method VARCHAR(20) DEFAULT 'ONLINE',
  operator_id INT,
  remark VARCHAR(255),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS shipments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  shipment_no VARCHAR(30) UNIQUE NOT NULL,
  batch_id INT NOT NULL,
  supplier_id INT NOT NULL,
  status ENUM('PREPARING','SHIPPED','ARRIVED') DEFAULT 'PREPARING',
  shipped_at DATETIME NULL,
  arrived_at DATETIME NULL,
  note VARCHAR(255),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS shipment_orders (
  shipment_id INT NOT NULL,
  order_id INT NOT NULL,
  PRIMARY KEY (shipment_id, order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS distributions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  plan_id INT NOT NULL,
  class_id INT NOT NULL,
  title VARCHAR(100),
  slot_start DATETIME NOT NULL,
  slot_end DATETIME NOT NULL,
  location VARCHAR(100),
  type ENUM('NORMAL','MAKEUP') DEFAULT 'NORMAL' COMMENT '正常发放/补领',
  status ENUM('SCHEDULED','DONE','CANCELLED') DEFAULT 'SCHEDULED',
  created_by INT,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS distribution_records (
  id INT AUTO_INCREMENT PRIMARY KEY,
  distribution_id INT NOT NULL,
  order_id INT NOT NULL,
  student_id INT NOT NULL,
  status ENUM('PENDING','SIGNED','MISSED') DEFAULT 'PENDING',
  signed_by VARCHAR(50),
  signed_at DATETIME NULL,
  UNIQUE KEY uq_dr (distribution_id, order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS aftersales (
  id INT AUTO_INCREMENT PRIMARY KEY,
  ticket_no VARCHAR(30) UNIQUE NOT NULL,
  order_id INT NOT NULL,
  order_item_id INT NULL,
  student_id INT NOT NULL,
  type ENUM('EXCHANGE','REISSUE','REFUND','COMPLAINT','ALLERGY','WRONG_PICKUP','MISSING') NOT NULL,
  item_desc VARCHAR(100),
  from_size VARCHAR(20), to_size VARCHAR(20),
  reason VARCHAR(500),
  status ENUM('SUBMITTED','PROCESSING','APPROVED','REJECTED','RESOLVED','CLOSED') DEFAULT 'SUBMITTED',
  handler_id INT NULL,
  resolution VARCHAR(500),
  refund_amount DECIMAL(10,2) NULL,
  created_by INT,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS supplier_assessments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  supplier_id INT NOT NULL,
  batch_id INT NULL,
  score_quality INT, score_timeliness INT, score_service INT,
  comment VARCHAR(500),
  created_by INT,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS notifications (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL,
  title VARCHAR(100),
  content VARCHAR(500),
  is_read TINYINT DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS events (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  entity VARCHAR(30) NOT NULL,
  entity_id INT NOT NULL,
  action VARCHAR(50) NOT NULL,
  actor_id INT,
  actor_name VARCHAR(50),
  detail VARCHAR(500),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  KEY idx_entity (entity, entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
